def normalize():
    """원본 먹이 그림처럼 그림의 맨 아랫줄을 15번째 줄(0부터 14)에 맞춘다.
       안 맞추면 발판 위에 붕 뜬 것처럼 보인다."""
    for i, (name, theme, rows) in enumerate(ART):
        low = max(y for y in range(16) if set(rows[y]) != {'.'})
        top = min(y for y in range(16) if set(rows[y]) != {'.'})
        d = 14 - low
        if d > 0: d = min(d, top)          # 위로 넘치지 않게
        if d == 0: continue
        blank = '.' * 16
        if d > 0:   nr = [blank] * d + rows[:16-d]
        else:       nr = rows[-d:] + [blank] * (-d)
        ART[i] = (name, theme, nr)

normalize()
