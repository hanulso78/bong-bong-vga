ART = []

def add(name, theme, rows):
    rows = [r for r in rows.strip('\n').split('\n')]
    assert len(rows) == 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
        assert set(r) <= set('.123'), (name, r)
    ART.append((name, theme, rows))


